export function errText(code: string | undefined, extra?: { left?: number; retry_in?: number }): string {
  if (code === 'locked') return (T.err.locked as (n: number) => string)(Math.max(1, Math.ceil((extra?.retry_in ?? 900) / 60)));
  const v = T.err[code ?? 'unknown'] ?? T.err.unknown;
  let msg = typeof v === 'function' ? v(0) : (v as string);
  if (code === 'bad_credentials' && extra?.left && extra.left <= 3) msg += ' ' + (T.err.left as (n: number) => string)(extra.left);
  return msg;
}
